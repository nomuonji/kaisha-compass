import MarkdownIt from "markdown-it";

// Cloudflare Pages Functions: this is the Pages-native replacement for Astro
// SSR on /features/. All other routes remain pre-rendered HTML in dist/.
const md = new MarkdownIt({ html: false, linkify: true });
const siteId = "kaisha-compass";
const slugPattern = /^[a-z0-9][a-z0-9-]*(?:\/[a-z0-9][a-z0-9-]*)*$/;
const marker = "KAISHA_COMPASS_PUBLIC_CMS_RENDER_TARGET";
const escape = (text) => String(text ?? "").replace(/[&<>"']/g, (char) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
}[char]));
const valid = (item) =>
  item && typeof item === "object" && item.siteId === siteId &&
  typeof item.slug === "string" && slugPattern.test(item.slug) &&
  typeof item.title === "string" && typeof item.summary === "string" &&
  typeof item.bodyMarkdown === "string";

async function queryCms(env, slug) {
  const endpoint = new URL("/api/public-content", env.PUBLIC_CMS_BASE_URL || "https://my-portal-agent.netlify.app");
  endpoint.searchParams.set("site", siteId);
  if (slug) endpoint.searchParams.set("slug", slug);
  else endpoint.searchParams.set("limit", "100");
  try {
    const response = await fetch(endpoint, { signal: AbortSignal.timeout(7000) });
    return response.ok ? await response.json() : null;
  } catch {
    return null;
  }
}
function listContent(items) {
  return `<p class="section-type-label topic-type">補足解説</p>
    <h1>実務と制度の補足解説</h1>
    <p class="cms-feature-intro">会社の一年を追う<a href="/#journey">15の場面</a>を主な学習経路として残し、各場面から派生する論点を記事で補足します。</p>` +
    (items.length ? `<div class="cms-feature-list">${items.map((item) =>
      `<article class="cms-feature-card"><h2><a href="/features/${encodeURI(item.slug)}/">${escape(item.title)}</a></h2><p>${escape(item.summary)}</p><p class="cms-feature-date">${escape(item.publishedAt?.slice(0, 10) || "")}</p></article>`
    ).join("")}</div>` : '<p class="cms-feature-empty">公開中の補足解説はありません。会社の一年と資料一覧は引き続き利用できます。</p>');
}
function articleContent(item) {
  return `<p class="cms-feature-breadcrumb"><a href="/features/">補足解説一覧</a> › ${escape(item.title)}</p>
    <article class="cms-feature-article">
      <p class="section-type-label topic-type">補足解説</p>
      <h1>${escape(item.title)}</h1>
      <p class="cms-feature-intro">${escape(item.summary)}</p>
      ${item.publishedAt ? `<p class="cms-feature-date">公開 ${escape(item.publishedAt.slice(0, 10))}</p>` : ""}
      <div class="cms-feature-body">${md.render(item.bodyMarkdown)}</div>
      <p><a href="/features/">補足解説一覧へ戻る</a></p>
    </article>`;
}
export async function serveCms({ request, env, params }, isIndex) {
  if (request.method !== "GET" && request.method !== "HEAD") return new Response(null, { status: 405 });
  const rawSlug = params?.slug;
  const candidate = Array.isArray(rawSlug) ? rawSlug.join("/") : rawSlug || "";
  // Pages may dispatch the collection root to the optional catch-all Function.
  // Empty slug always means the CMS index, irrespective of the matched file.
  const slug = isIndex || candidate === "" ? null : candidate;
  if (slug !== null && !slugPattern.test(slug)) return new Response("Not found", { status: 404 });

  // The template is generated by the same Astro layouts and styles as the static site.
  const templateUrl = new URL("/cms-page-template/", request.url);
  const asset = await env.ASSETS.fetch(new Request(templateUrl));
  if (!asset.ok) return new Response("Site layout unavailable", { status: 503 });
  let html = await asset.text();
  if (!html.includes(marker)) return new Response("Site layout marker missing", { status: 503 });

  const data = await queryCms(env, slug);
  const item = slug && valid(data?.item) && data.item.slug === slug ? data.item : null;
  const items = !slug && Array.isArray(data?.items) ? data.items.filter(valid).slice(0, 100) : [];
  const notFound = Boolean(slug && !item);
  const title = item?.seo?.title || item?.title || (notFound ? "記事が見つかりません" : "補足解説");
  const summary = item?.seo?.description || item?.summary || "会社の設立・運営に役立つ補足解説。";
  const section = notFound ?
    '<section><h1>記事が見つかりません</h1><a href="/features/">補足解説一覧へ戻る</a></section>' :
    item ? articleContent(item) : listContent(items);
  const noindex = notFound || (item ? item.seo?.noindex === true : items.length === 0);
  html = html.replace(marker, section);
  html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${escape(title)} | Kaisha Compass</title>`);
  html = html.replace(/<meta name="description" content="[^"]*"\s*\/?>/,
    `<meta name="description" content="${escape(summary)}" />`);
  if (!noindex) html = html.replace(/<meta name="robots" content="noindex,nofollow"\s*\/?>/, "");
  const canonical = new URL(request.url);
  html = html.replace(/<link rel="canonical" href="[^"]*"\s*\/?>/,
    `<link rel="canonical" href="${escape(canonical.origin + canonical.pathname)}" />`);
  return new Response(request.method === "HEAD" ? null : html, {
    status: notFound ? 404 : 200,
    headers: { "content-type": "text/html; charset=utf-8", "cache-control": "public, max-age=0, s-maxage=120" },
  });
}
